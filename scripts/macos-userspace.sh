#!/usr/bin/env bash
# macOS Tailscale without root.
#
# The supported install is the Tailscale app, or `sudo brew services start
# tailscale`, which creates a tunnel interface. Use this script only when you
# cannot use admin rights. It runs tailscaled as your user with userspace
# networking.
#
# Trade-off: other tailnet devices can still reach `tailscale serve`, which is
# what phones and laptops need. This Mac itself has no tunnel interface, so
# local programs reach tailnet names through the SOCKS proxy on 127.0.0.1:1055.
# tailscaled also listens on a high TCP port on all interfaces so peers can
# connect. Prefer the app when you can.
#
#   ./scripts/macos-userspace.sh
#   ./scripts/macos-setup.sh
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
. "$HERE/lib.sh"

[ "$(uname -s)" = "Darwin" ] || die "this helper is for macOS"

td="$(command -v tailscaled || true)"
[ -n "$td" ] || die "tailscaled is not installed. brew install tailscale, then re-run. The daemon runs as you."

state="${HOME}/.local/state/tailscale"
sock="${state}/tailscaled.sock"
libdir="${HOME}/.local/lib/opencode-vps"
conf="${XDG_CONFIG_HOME:-$HOME/.config}/opencode-vps"
log="${HOME}/Library/Logs/opencode-vps-tailscaled.log"
plist="${HOME}/Library/LaunchAgents/com.opencode.vps.tailscaled.plist"
wrapper="${libdir}/userspace-tailscaled.sh"

mkdir -p "$state" "$libdir" "$conf" "${HOME}/Library/Logs" "${HOME}/Library/LaunchAgents"
( umask 077; printf '%s\n' "$sock" > "${conf}/tailscale.socket" )

cat > "$wrapper" <<EOF
#!/bin/sh
# Generated by scripts/macos-userspace.sh. Safe to overwrite.
set -eu
umask 077
STATE='${state}'
SOCK='${sock}'
TD='${td}'
mkdir -p "\$STATE"
"\$TD" --tun=userspace-networking --statedir="\$STATE" --socket="\$SOCK" --socks5-server=127.0.0.1:1055 &
pid=\$!
trap 'kill "\$pid" 2>/dev/null || true' TERM INT
i=0
while [ "\$i" -lt 50 ]; do
	if [ -S "\$SOCK" ]; then
		chmod 600 "\$SOCK" || true
		break
	fi
	i=\$((i + 1))
	sleep 0.2
done
wait "\$pid"
EOF
chmod 755 "$wrapper"

cat > "$plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>Label</key>
	<string>com.opencode.vps.tailscaled</string>
	<key>ProgramArguments</key>
	<array>
		<string>${wrapper}</string>
	</array>
	<key>RunAtLoad</key>
	<true/>
	<key>KeepAlive</key>
	<true/>
	<key>ThrottleInterval</key>
	<integer>10</integer>
	<key>StandardOutPath</key>
	<string>${log}</string>
	<key>StandardErrorPath</key>
	<string>${log}</string>
</dict>
</plist>
EOF
chmod 644 "$plist"

uid="$(id -u)"
# The Homebrew formula's agent needs root and crash-loops in a user session.
launchctl bootout "gui/${uid}/homebrew.mxcl.tailscale" 2>/dev/null || true
launchctl bootout "gui/${uid}/com.opencode.vps.tailscaled" 2>/dev/null || true
launchctl bootstrap "gui/${uid}" "$plist"

log "waiting for tailscaled"
ready=0
for _ in $(seq 1 30); do
	if [ -S "$sock" ] && ts ip -4 >/dev/null 2>&1; then
		ready=1
		break
	fi
	sleep 1
done
chmod 600 "$sock" 2>/dev/null || true

if [ "$ready" -eq 1 ]; then
	ok "tailscale connected: $(ts ip -4 | head -n1) ($(tailnet_dns))"
	exit 0
fi

warn "tailscaled is running but this node is not logged in."
warn "Approve this in a browser, then re-run ./scripts/macos-setup.sh:"
warn "  tailscale --socket '${sock}' up --hostname '$(hostname -s)'"
exit 2
